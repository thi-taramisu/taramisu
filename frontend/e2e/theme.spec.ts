import { expect, test } from '@playwright/test'

test('defaults to light even with a dark system preference; persists across pages and reloads', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/projects')
  const toggle = page.getByRole('button', { name: 'Dark mode' })
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  await toggle.click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  expect(await page.evaluate("localStorage.getItem('taramisu.theme')")).toBe('dark')
  await page.reload()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('link', { name: 'Headlamp System (example)' }).click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await toggle.click()
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  await page.reload()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
})

test('applies the saved mode before the React application can execute', async ({ page }) => {
  await page.addInitScript("localStorage.setItem('taramisu.theme', 'dark'); localStorage.setItem('taramisu.colorScheme', 'ocean')")
  // With the application bundles blocked, only the early theme bootstrap can apply the preference.
  await page.route('**/assets/*.js', (route) => route.abort())
  await page.goto('/projects')
  await expect(page.locator('html')).toHaveClass(/dark/)
  expect(await page.locator('html').evaluate((element) => element.getAttribute('style'))).toContain('color-scheme: dark')
  await expect(page.locator('html')).toHaveAttribute('data-color-scheme', 'ocean')
  await expect(page.locator('#root')).toBeEmpty()
})

test('invalid saved values fall back to light without consulting the OS preference', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.addInitScript("localStorage.setItem('taramisu.theme', 'invalid'); localStorage.setItem('taramisu.colorScheme', 'invalid')")
  await page.goto('/projects')
  await expect(page.getByRole('button', { name: 'Dark mode' })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  await expect(page.getByRole('combobox', { name: 'Color scheme' })).toHaveValue('neutral')
})

test('item diagram, settings and risk views remain usable in dark mode', async ({ page }) => {
  await page.addInitScript("localStorage.setItem('taramisu.theme', 'dark')")
  await page.goto('/projects/headlamp/items/i-01')
  await expect(page.locator('.react-flow.dark')).toBeVisible()
  await expect(page.getByText('Body control ECU', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Assets (4)', exact: true }).click()
  await expect(page.getByRole('table')).toBeVisible()
  await page.getByRole('button', { name: 'Add Asset', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: 'Risks', exact: true }).click()
  await expect(page.getByRole('table')).toBeVisible()
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('textbox', { name: /Name/ })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Dark mode' })).toHaveAttribute('aria-pressed', 'true')
})

test('selects all palettes globally, independently of dark mode, and restores the selection', async ({ page }) => {
  await page.goto('/projects')
  const select = page.getByRole('combobox', { name: 'Color scheme' })
  const toggle = page.getByRole('button', { name: 'Dark mode' })
  const backgrounds: string[] = []
  for (const scheme of ['neutral', 'ocean', 'iris']) {
    await select.selectOption(scheme)
    await expect(page.locator('html')).toHaveAttribute('data-color-scheme', scheme)
    await expect(toggle).toHaveAttribute('aria-pressed', 'false')
    backgrounds.push(await page.evaluate('getComputedStyle(document.body).backgroundColor'))
    await toggle.click()
    await expect(page.locator('html')).toHaveAttribute('data-color-scheme', scheme)
    await expect(toggle).toHaveAttribute('aria-pressed', 'true')
    await toggle.click()
  }
  expect(new Set(backgrounds).size).toBe(3)
  await toggle.click()
  await page.getByRole('link', { name: 'Headlamp System (example)' }).click()
  await expect(select).toHaveValue('iris')
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(select).toHaveValue('iris')
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  expect(await page.evaluate("localStorage.getItem('taramisu.colorScheme')")).toBe('iris')
})
