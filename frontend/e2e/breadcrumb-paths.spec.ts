import { expect, test } from '@playwright/test'

test('selects shared hierarchy paths from the tree and breadcrumbs across tabs and history', async ({ page }) => {
  await page.goto('/projects/headlamp/damage-scenarios/ds-01/relations')
  await page.getByRole('region', { name: 'Assets', exact: true }).getByRole('button', { name: 'Add Asset', exact: true }).click()
  await page.getByRole('dialog', { name: 'Add Asset', exact: true }).getByRole('button', { name: /AS-2 Body control ECU firmware/ }).click()
  const tree = page.getByRole('navigation', { name: 'Project elements' })
  const occurrences = tree.getByRole('link', { name: /^DS-1 / })
  await expect(occurrences).toHaveCount(2)
  await occurrences.nth(1).click()
  const breadcrumbs = page.getByRole('navigation', { name: 'Breadcrumbs' })
  await expect(breadcrumbs.getByRole('link', { name: /AS-2/ })).toBeVisible()
  await expect(tree.locator('a[aria-current="page"]')).toHaveCount(1)
  await page.getByRole('link', { name: 'Impact', exact: true }).click()
  await expect(breadcrumbs.getByRole('link', { name: /AS-2/ })).toBeVisible()
  await breadcrumbs.getByRole('button', { name: 'Select hierarchy path' }).click()
  await expect(page.getByRole('menuitemradio')).toHaveCount(2)
  await page.getByRole('menuitemradio', { name: /AS-1 Headlamp on\/off command/ }).click()
  await expect(breadcrumbs.getByRole('link', { name: /AS-1/ })).toBeVisible()
  await page.goBack()
  await expect(breadcrumbs.getByRole('link', { name: /AS-2/ })).toBeVisible()
  const selected = new URL(page.url()).searchParams.get('hierarchy')
  await page.getByRole('switch', { name: 'Graph', exact: true }).click()
  expect(new URL(page.url()).searchParams.get('hierarchy')).toBe(selected)
  await expect(breadcrumbs.getByRole('link', { name: /AS-2/ })).toBeVisible()
})
