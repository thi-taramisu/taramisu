#!/usr/bin/env python3
"""Generate Authentik branding from the frontend's palettes (stdlib only)."""
import argparse
from pathlib import Path
import re
from textwrap import indent

ROOT = Path(__file__).resolve().parents[2]
THEMES = {name: ROOT / f'frontend/src/styles/themes/{name}.css'
          for name in ('neutral', 'ocean', 'iris')}
TEMPLATE = ROOT / 'iam/branding/branding.yaml.template'
OUTPUT = ROOT / 'iam/blueprints/branding.yaml'
TOKENS = ('background', 'foreground', 'card', 'card-foreground', 'primary',
          'primary-foreground', 'muted', 'muted-foreground', 'border', 'input',
          'ring', 'destructive', 'radius')


def read_palette(css: str, name: str) -> tuple[dict, dict]:
    # Support our flat light/dark files, not arbitrary CSS.
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    blocks = re.findall(r'([^{}]+)\{([^{}]*)\}', css)
    selectors = [re.sub(r'\s+', '', selector) for selector, _ in blocks]
    expected = ([':root,[data-color-scheme]', '.dark'] if name == 'neutral'
                else [f'[data-color-scheme="{name}"]', f'[data-color-scheme="{name}"].dark'])
    if selectors != expected:
        raise ValueError(f'Expected the flat light/dark selectors for {name}')
    return tuple(dict(re.findall(r'--([\w-]+)\s*:\s*([^;]+);', body)) for _, body in blocks)


def generate(themes: dict[str, str], template: str) -> str:
    base_light, base_dark = read_palette(themes['neutral'], 'neutral')
    rules = []
    for name in THEMES:
        light, dark = read_palette(themes[name], name)
        # Palette files load after Neutral, so palette light declarations also apply in dark mode.
        dark = base_light | base_dark | (light if name != 'neutral' else {}) | dark
        light = base_light | light
        declarations = []
        for token in TOKENS:
            day, night = light[token].strip(), dark[token].strip()
            pattern = r'\d+(?:\.\d+)?rem' if token == 'radius' else r'#[0-9a-fA-F]{6}'
            if not all(re.fullmatch(pattern, value) for value in (day, night)):
                raise ValueError(f'Unsupported value for {name} --{token}: expected hex colours or rem radius')
            if token == 'radius' and day != night:
                raise ValueError('Shared branding requires the same radius in light and dark modes')
            value = day if day == night else f'light-dark({day}, {night})'
            declarations.append(f'  --taramisu-{token}: {value};')
        selector = ('ak-flow-executor' if name == 'neutral'
                    else f'html[data-color-scheme="{name}"] ak-flow-executor')
        rules.append(selector + ' {\n' + '\n'.join(declarations) + '\n}')
    if template.count('@@THEME@@') != 1:
        raise ValueError('Expected exactly one @@THEME@@ placeholder')
    return '# Generated by iam/branding/generate.py; edit the palettes or branding template.\n' + template.replace(
        '@@THEME@@', indent('\n'.join(rules), '        ').lstrip())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the committed blueprint is stale')
    args = parser.parse_args()
    result = generate({name: path.read_text() for name, path in THEMES.items()}, TEMPLATE.read_text())
    if args.check:
        if OUTPUT.read_text() != result:
            parser.exit(1, 'Branding is stale. Run: python3 iam/branding/generate.py\n')
        print('Authentik branding matches the frontend palettes.')
    else:
        OUTPUT.write_text(result)
        print('Generated iam/blueprints/branding.yaml')


if __name__ == '__main__':
    main()
